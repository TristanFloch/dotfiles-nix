"""Generate lua-language-server types for the actions the Rex app offers.

Only a running Rex app can list its actions, so this can't run at build
time. It does nothing when `rex` isn't on PATH. The rest of the `rex` API,
which doesn't change with the app version, is hand-written in rex.d.lua.

usage: rex-lua-types [OUTPUT]
"""
import json
import logging
import os
import shutil
import subprocess
import sys

log = logging.getLogger("rex-lua-types")

DEFAULT_OUTPUT = "~/.cache/rex-lua-types/actions.lua"

BIND_DOC = """\
---Binds a key to an action, with optional arguments for it.
---
---`key` is a single key (`"cmd+d"`), a sequence written with `>` (`"g>g"`),
---or either one prefixed with a mode and a slash (`"resize/h"`).
---
---The function form is called as `fn(ctx, ev)` and returns `true` to mark
---the key as handled. It isn't allowed in a mode.
---@param key string
---@param action rex.ActionName
---@param args? table<string, any>
---@overload fun(key: string, fn: rex.KeyHandler)"""

QUEUE_DOC = """\
---Asks the client to perform one of its own actions, such as `pane.zoom`.
---In an action, queued actions run after `run` returns.
---@param name rex.ActionName
---@param args? table<string, any>"""

JSON_TYPES = {
    "string": "string",
    "integer": "integer",
    "number": "number",
    "boolean": "boolean",
    "array": "any[]",
    "object": "table",
}


def query(*args):
    # Never start a server just to list its actions.
    argv = ["rex", "--autostart=false", "--timeout=5s", *args, "--json"]
    result = subprocess.run(argv, capture_output=True, text=True, timeout=30)
    if result.returncode != 0:
        raise RuntimeError(result.stderr.strip() or f"{' '.join(args)} failed")
    return json.loads(result.stdout)


def fetch_actions():
    clients = query("client", "ls")["clients"]
    apps = [c for c in clients if c.get("info", {}).get("kind") == "app"]
    if not apps:
        raise RuntimeError("no Rex app is connected")
    info = apps[0]["info"]
    actions = query("-C", apps[0]["client_id"], "actions")["actions"]
    source = f"{info.get('name', 'Rex')} {info.get('version', '')}".strip()
    return source, actions


def lua_type(schema):
    if "enum" in schema:
        return "|".join(json.dumps(value) for value in schema["enum"])
    types = schema.get("type", "any")
    types = types if isinstance(types, list) else [types]
    lua_types = [JSON_TYPES.get(t, "any") for t in types if t != "null"]
    return "|".join(lua_types) or "any"


def one_line(text):
    return " ".join(text.split())


def render(source, actions):
    lines = [
        "---@meta",
        f"-- Generated by rex-lua-types from {source}. Do not edit.",
        "",
        "---@alias rex.ActionName",
    ]
    for action in actions:
        line = f"---| {json.dumps(action['name'])}"
        if action.get("title"):
            line += f" # {one_line(action['title'])}"
        lines.append(line)
    lines += ["---| string # A custom action defined with rex.action", ""]

    overloads = []
    for action in actions:
        schema = action.get("args") or {}
        properties = schema.get("properties")
        if not properties:
            continue
        name, required = action["name"], set(schema.get("required", []))
        lines.append(f"---@class rex.args.{name}")
        for field, spec in properties.items():
            optional = "" if field in required else "?"
            doc = f"{lua_type(spec)} {one_line(spec.get('description', ''))}"
            lines.append(f"---@field {field}{optional} {doc}".rstrip())
        lines.append("")
        args = "args" if required else "args?"
        overloads.append(f"{json.dumps(name)}, {args}: rex.args.{name}")

    lines.append(BIND_DOC)
    lines += [f"---@overload fun(key: string, action: {o})" for o in overloads]
    lines += ["function rex.bind(key, action, args) end", "", QUEUE_DOC]
    lines += [f"---@overload fun(name: {o})" for o in overloads]
    lines += ["function rex.client.queue(name, args) end", ""]
    return "\n".join(lines)


def main():
    logging.basicConfig(format="%(name)s: %(message)s", level=logging.INFO)
    output = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_OUTPUT
    output = os.path.expanduser(output)
    if shutil.which("rex") is None:
        log.info("rex isn't on PATH; nothing to do")
        return
    try:
        source, actions = fetch_actions()
    except (RuntimeError, OSError, ValueError, KeyError,
            subprocess.TimeoutExpired) as error:
        if os.path.exists(output):
            log.warning("%s; keeping %s", error, output)
            return
        # Without this file rex.bind would be undefined, so write one
        # with no actions.
        log.warning("%s; writing %s without actions", error, output)
        source, actions = "no running Rex app", []

    os.makedirs(os.path.dirname(output), exist_ok=True)
    with open(output + ".tmp", "w") as file:
        file.write(render(source, actions))
    os.replace(output + ".tmp", output)
    if actions:
        log.info("wrote %d actions from %s to %s",
                 len(actions), source, output)


if __name__ == "__main__":
    main()
